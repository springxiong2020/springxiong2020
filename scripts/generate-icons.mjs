import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { resolve } from "node:path";
import { format } from "prettier";

const root = fileURLToPath(new URL("../", import.meta.url));
const families = { copy: "regular", github: "brands" };
const styles = new Set(["solid", "regular", "brands"]);
const names = new Set();

function scan(directory) {
  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    const path = resolve(directory, entry.name);
    if (entry.isDirectory()) scan(path);
    else if (/\.(vue|js)$/.test(entry.name)) {
      const source = readFileSync(path, "utf8");
      for (const [, name] of source.matchAll(/\bfa-([a-z][a-z0-9-]*)\b/g)) {
        if (!styles.has(name)) names.add(name);
      }
    }
  }
}
scan(resolve(root, "src"));

const { version } = JSON.parse(
  readFileSync(resolve(root, "node_modules/@fortawesome/fontawesome-free/package.json"), "utf8"),
);
const header = `/*!
 * Selected icons from Font Awesome Free ${version} by Fonticons, Inc.
 * https://fontawesome.com — Icons: CC BY 4.0
 * https://creativecommons.org/licenses/by/4.0/
 * Generated by npm run icons:generate. Do not edit manually.
 */\n`;
const base = `.fa-solid, .fa-regular, .fa-brands {
  display: inline-block;
  flex-shrink: 0;
  width: 1.25em;
  height: 1em;
  vertical-align: -0.125em;
  background-color: currentColor;
  -webkit-mask: var(--icon-svg, linear-gradient(transparent, transparent)) center / contain no-repeat;
  mask: var(--icon-svg, linear-gradient(transparent, transparent)) center / contain no-repeat;
}
@media (forced-colors: active) {
  .fa-solid, .fa-regular, .fa-brands {
    forced-color-adjust: none;
    background-color: CanvasText;
  }
}\n`;
const rules = [...names].sort().map((name) => {
  const family = families[name] || "solid";
  const path = resolve(
    root,
    `node_modules/@fortawesome/fontawesome-free/svgs/${family}/${name}.svg`,
  );
  const svg = readFileSync(path, "utf8")
    .replace(/<!--[\s\S]*?-->/g, "")
    .trim();
  return `.fa-${family}.fa-${name} { --icon-svg: url("data:image/svg+xml,${encodeURIComponent(svg)}"); }`;
});
const output = await format(header + base + rules.join("\n") + "\n", {
  parser: "css",
});
const target = resolve(root, "src/icons.css");
if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== output) {
    throw new Error("图标清单已变化，请运行 npm run icons:generate");
  }
} else {
  writeFileSync(target, output);
}
